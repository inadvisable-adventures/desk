def test_detect_kind():
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as d:
        job_dir = Path(d) / "job"
        job_dir.mkdir()
        check("neither file present: None", detect_kind(job_dir) is None)
        (job_dir / "main.py").write_text("print('hi')\n")
        check("only main.py: python", detect_kind(job_dir) == "python")
        (job_dir / "Cargo.toml").write_text(_CARGO_TOML)
        check("both present: ambiguous, None", detect_kind(job_dir) is None)
        (job_dir / "main.py").unlink()
        check("only Cargo.toml: rust", detect_kind(job_dir) == "rust")


def test_compute_version_hash_excludes_target():
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as d:
        job_dir = Path(d) / "job"
        _write_rust_job(job_dir)
        before = compute_version_hash(job_dir)
        (job_dir / "target" / "release").mkdir(parents=True)
        (job_dir / "target" / "release" / "greet_rust").write_bytes(b"fake binary bytes")
        (job_dir / "target" / "release" / "extra.d").write_text("build metadata\n")
        after = compute_version_hash(job_dir)
        check("hash unaffected by files under target/", before == after)


def test_compute_version_hash_excludes_root_cargo_lock():
    """TODO 94a2fa2: a real bug found via this item's own verification
    -- `cargo build` writes/updates Cargo.lock at the project root (not
    under target/) the first time it runs without one, which would
    otherwise make a job's very first real build look like a source
    change too, exactly like the target/ case above."""
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as d:
        job_dir = Path(d) / "job"
        _write_rust_job(job_dir)
        before = compute_version_hash(job_dir)
        (job_dir / "Cargo.lock").write_text('# auto-generated by cargo build\nversion = 3\n')
        after = compute_version_hash(job_dir)
        check("hash unaffected by a root-level Cargo.lock appearing", before == after)
        # A nested file that merely happens to be *named* Cargo.lock
        # (not the real root lockfile) is not exempted -- the exclusion
        # is deliberately narrow (see compute_version_hash's own
        # docstring), not "ignore every file named Cargo.lock anywhere".
        (job_dir / "src" / "Cargo.lock").write_text("not the real one\n")
        nested = compute_version_hash(job_dir)
        check("a nested src/Cargo.lock (not the real root one) still affects the hash", nested != after)


