def test_run_rust_job_builds_and_executes():
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as d:
        directory = Path(d)
        job_dir = installed_job_dir(directory, "greet")
        _write_rust_job(job_dir)
        real_hash = compute_version_hash(job_dir)
        window = _FakeWindowForRun(
            directory,
            [InstalledJobDefinition(name="greet", version_hash=real_hash, installed_at="2026-01-01T00:00:00")],
        )

        results = []
        window.run_installed_job("greet", None, lambda ok, out, err, tb: results.append((ok, out, err, tb)))
        ok = _wait(lambda: results, timeout=120.0)
        check("run_installed_job eventually reports a result (build + run)", ok)
        if results:
            run_ok, stdout, stderr, tb = results[0]
            check("the rust binary ran successfully", run_ok, )
            check("stdout captured the job's own output", "hello from rust" in stdout)
            check("CONFIG_PATH env var was unset (None) when no config_path given", "CONFIG=None" in stdout)
            check("no traceback on success", tb == "")
        binary = job_dir / "target" / "release" / "greet_rust"
        check("a real compiled binary now exists under target/release/", binary.is_file())

        # Second run: the binary should not need rebuilding (mtime
        # unchanged) and should still execute correctly.
        first_mtime = binary.stat().st_mtime
        results2 = []
        window.run_installed_job("greet", None, lambda ok, out, err, tb: results2.append((ok, out, err, tb)))
        _wait(lambda: results2, timeout=30.0)
        check("second run does not rebuild the binary", binary.stat().st_mtime == first_mtime)
        check("second run still succeeds", results2 and results2[0][0])


def test_run_rust_job_config_and_needs_env_vars():
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as d:
        directory = Path(d)
        job_dir = installed_job_dir(directory, "greet")
        _write_rust_job(job_dir)
        (job_dir / "job.json").write_text(json.dumps({"needs": ["some_key"]}))
        real_hash = compute_version_hash(job_dir)
        window = _FakeWindowForRun(
            directory,
            [InstalledJobDefinition(name="greet", version_hash=real_hash, installed_at="2026-01-01T00:00:00")],
        )
        window.current_desk.state["some_key"] = StateEntry(value=42, edit="set by test")

        cfg = directory / "cfg.json"
        cfg.write_text("{}")
        results = []
        window.run_installed_job(
            "greet", str(cfg), lambda ok, out, err, tb: results.append((ok, out, err, tb))
        )
        ok = _wait(lambda: results, timeout=120.0)
        check("run with config_path + needs eventually reports a result", ok)
        if results:
            run_ok, stdout, stderr, tb = results[0]
            check("run succeeded", run_ok)
            check("DESK_JOB_CONFIG_PATH reached the job", f'CONFIG=Some("{cfg}")' in stdout)
            check("DESK_JOB_NEEDS_PATH reached the job with the resolved value", '"some_key"' in stdout and "42" in stdout)
        needs_file = directory / ".desk_temp" / "installed-job-needs" / "greet.json"
        check("the needs file itself matches what get_state returns", json.loads(needs_file.read_text()) == {"some_key": {"value": 42, "edit": "set by test"}})


def test_stale_source_refuses_run_and_reinstall_clears_it():
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as d:
        directory = Path(d)
        job_dir = installed_job_dir(directory, "greet")
        _write_rust_job(job_dir)
        real_hash = compute_version_hash(job_dir)
        window = _FakeWindowForRun(
            directory,
            [InstalledJobDefinition(name="greet", version_hash=real_hash, installed_at="2026-01-01T00:00:00")],
        )
        (job_dir / "src" / "main.rs").write_text(_MAIN_RS.replace("hello from rust", "hello v2"))
        try:
            window.run_installed_job("greet", None, lambda *a: None)
            check("stale source raises ValueError before anything runs", False)
        except ValueError as e:
            check("stale source raises ValueError before anything runs", "no longer matches" in str(e))
        ok, _message = window.install_job("greet")
        check("re-installing succeeds", ok)
        results = []
        window.run_installed_job("greet", None, lambda ok, out, err, tb: results.append((ok, out, err, tb)))
        _wait(lambda: results, timeout=120.0)
        check("after re-install, run succeeds with the new source", results and results[0][0] and "hello v2" in results[0][1])


