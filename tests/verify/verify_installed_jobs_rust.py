# A minimal, dependency-free Cargo project -- see this file's own
# header comment for why no [dependencies].
_CARGO_TOML = """[package]
name = "greet_rust"
version = "0.1.0"
edition = "2021"
"""
_MAIN_RS = """use std::env;
use std::fs;

fn main() {
    let config = env::var("DESK_JOB_CONFIG_PATH").ok();
    println!("CONFIG={:?}", config);
    match env::var("DESK_JOB_NEEDS_PATH") {
        Ok(needs_path) => {
            let content = fs::read_to_string(&needs_path).unwrap_or_default();
            println!("NEEDS={}", content);
        }
        Err(_) => println!("NEEDS=None"),
    }
    println!("hello from rust");
}
"""


def _write_rust_job(job_dir: Path, main_rs: str = _MAIN_RS) -> None:
    (job_dir / "src").mkdir(parents=True, exist_ok=True)
    (job_dir / "Cargo.toml").write_text(_CARGO_TOML)
    (job_dir / "src" / "main.rs").write_text(main_rs)


